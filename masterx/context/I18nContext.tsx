const TRANSLATIONS: Record<LangCode, T> = { en, es, fr, de, pt, ja, zh, ko, it, ru, hi };

// ─── Context ─────────────────────────────────────────────────────────────────
interface I18nContextValue {
  t: T;
  lang: LangCode;
}

const I18nContext = createContext<I18nContextValue>({ t: en, lang: 'en' });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const { settings } = useAppData();
  const lang: LangCode = settings.language in TRANSLATIONS ? settings.language : 'en';
  const value = useMemo(() => ({ t: TRANSLATIONS[lang], lang }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

